use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::{Data, DeriveInput, Fields, Ident, Type};

pub(crate) fn expand(ast: &DeriveInput) -> syn::Result<TokenStream> {
    let name = &ast.ident;

    let fields = match &ast.data {
        Data::Struct(s) => match &s.fields {
            Fields::Named(f) => &f.named,
            _ => {
                return Err(syn::Error::new_spanned(name, "IntoBatchedStructSpace requires a struct with named fields"));
            }
        },
        _ => {
            return Err(
                syn::Error::new_spanned(
                    name,
                    "IntoBatchedStructSpace can only be derived for struct currently"
                )
            );
        }
    };

    if fields.is_empty() {
        return Err(syn::Error::new_spanned(name, "IntoBatchedStructSpace requires at least one field"));
    }

    let (impl_generics, ty_generics, where_clause) = ast.generics.split_for_impl();
    let field_idents: Vec<Ident> = fields.iter().map(|f| f.ident.clone().unwrap()).collect();
    let field_tys: Vec<Type> = fields.iter().map(|f| f.ty.clone()).collect();

    let batched_space_ident = format_ident!("Batched{}", name);
    let batched_element_ident = format_ident!("Batched{}Element", name);

    let batched_space_doc = format!("batched space of struct space {}. generated by proc-macro `IntoBatchedStructSpace`", quote! {#name});

    let bufs: Vec<Ident> = field_idents.iter().map(|i| format_ident!("__f_{}", i)).collect();
    let fst_buf = bufs[0].clone();

    Ok(quote! {
        #[doc = #batched_space_doc]
        #[derive(::bake_rl::core::env::space::BatchedStructSpace, Debug, Clone)]
        pub struct #batched_space_ident {
            #(
                ///
                pub #field_idents: <#field_tys as ::bake_rl::core::env::space::IntoBatchedSpace>::Batched,
            )*
        }

        impl #impl_generics ::bake_rl::core::env::space::IntoBatchedSpace for #name #ty_generics #where_clause {
            type Batched = #batched_space_ident;

            fn into_batched(spaces: &[Self], device: &::bake_rl::burn::prelude::Device) -> Self::Batched {
                assert!(!spaces.is_empty(), "IntoBatchedSpace::into_batched: given `spaces` is empty");
                let n = spaces.len();
                #(let mut #bufs = ::std::vec::Vec::with_capacity(n);)*

                for space in spaces {
                    let Self { #(#field_idents, )* } = ::std::clone::Clone::clone(space);
                    #(#bufs.push(#field_idents);)*
                }

                Self::Batched {
                    #(#field_idents: ::bake_rl::core::env::space::IntoBatchedSpace::into_batched(&#bufs, device),)*
                }
            }

            fn bind(elems: Vec<Self::Element>, device: &::bake_rl::burn::prelude::Device) -> <Self::Batched as ::bake_rl::core::env::space::BatchedSpace>::Element {
                assert!(!elems.is_empty(), "IntoBatchedSpace::bind: given `elems` is empty");
                let n = elems.len();
                #(let mut #bufs = ::std::vec::Vec::with_capacity(n);)*

                for elem in elems {
                    let Self::Element { #(#field_idents, )* } = elem;
                    #(#bufs.push(#field_idents);)*
                }

                #batched_element_ident {
                    #(#field_idents: <#field_tys as ::bake_rl::core::env::space::IntoBatchedSpace>::bind(#bufs, device),)*
                }
            }

            fn unbind(elem: <Self::Batched as ::bake_rl::core::env::space::BatchedSpace>::Element) -> Vec<Self::Element> {
                #(let mut #bufs = <#field_tys as ::bake_rl::core::env::space::IntoBatchedSpace>::unbind(elem.#field_idents);)*

                let __n = #fst_buf.len();

                #(let mut #bufs = #bufs.into_iter();)*
                (0..__n).map(|_| Self::Element { #(#field_idents: #bufs.next().unwrap(), )* }).collect()
            }
        }
    })
}