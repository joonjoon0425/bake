use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::{Fields, Ident, ItemStruct, Type};
use super::utils::to_pascal_case;

pub(crate) fn expand(ast: &ItemStruct) -> syn::Result<TokenStream> {
    let name = &ast.ident;
    let vis = ast.vis.clone();
    let attrs = ast.attrs.clone();

    let fields = match &ast.fields {
        Fields::Named(f) => &f.named,
        _ => {
            return Err(syn::Error::new_spanned(name, "`batched_struct_space` requires a struct with named fields"));
        }
    };

    if fields.is_empty() {
        return Err(syn::Error::new_spanned(name, "`batched_struct_space` requires at least one field"));
    }

    let (_impl_generics, ty_generics, _where_clause) = ast.generics.split_for_impl();
    let field_idents: Vec<Ident> = fields.iter().map(|f| f.ident.clone().unwrap()).collect();
    let fst_field = &field_idents[0];
    let field_tys: Vec<Type> = fields.iter().map(|f| f.ty.clone()).collect();
    let field_attrs: Vec<_> = fields.iter().map(|f| f.attrs.clone()).collect();
    let field_vis: Vec<_> = fields.iter().map(|f| f.vis.clone()).collect();

    let generalized_space_ident = format_ident!("{}Generic", name);
    let generalized_space_element_ident = format_ident!("{}GenericElement", name);
    let element_alias_ident = format_ident!("{}Element", name);
    let generic_ty_idents: Vec<Ident> = fields.iter().enumerate().map(|(u, _)| format_ident!("__S{}", u)).collect();

    let field_transform_idents: Vec<Ident> = fields.iter().map(|f| format_ident!("transform_{}", &f.ident.clone().unwrap())).collect();
    let field_transform_struct_idents: Vec<Ident> = field_transform_idents.iter().map(|f| format_ident!("{}{}", name, to_pascal_case(&f.to_string()))).collect();
    let field_transform_struct_output_spaces: Vec<Vec<TokenStream>> = generic_ty_idents.iter().enumerate().map(|(u, _)| fields.iter().enumerate().map(|(u_inner, _)| { if u == u_inner { let gk = format_ident!("__S{u}"); quote!( <BatchedTransformer as ::bake_rl::core::env::space_transform::BatchedSpaceTransform<#gk>>::Applied ) } else { let tmp = format_ident!("__S{}", u_inner); quote! { #tmp } }}).collect()).collect();
    let field_transform_struct_output_space_structs: Vec<Vec<TokenStream>> = field_idents.iter().enumerate().map(|(u, _)| field_idents.iter().enumerate().map(|(u_inner, field)| { if u == u_inner { quote!{ ::bake_rl::core::env::space_transform::BatchedSpaceTransform::transform_space(&self.transformer, &applicant.#field) } } else { quote!{applicant.#field.clone()}}}).collect()).collect();
    let field_transform_struct_output_elements: Vec<Vec<TokenStream>> = field_idents.iter().enumerate().map(|(u, _)| field_idents.iter().enumerate().map(|(u_inner, field)| { if u == u_inner { quote!{ ::bake_rl::core::env::space_transform::BatchedSpaceTransform::transform_element(&mut self.transformer, &applicant.#field, element.#field) } } else { quote!{element.#field}}}).collect()).collect();
    // let field_transform_struct_output_elements: Vec<Vec<TokenStream>> = generic_ty_idents.iter().enumerate().map(|(u, _)| fields.iter().enumerate().map(|(u_inner, _)| { if u == u_inner { quote!( <<Transformer as ::bake_rl::core::env::space_transform::SpaceTransform>::Applied as ::bake_rl::env::space::Space>::Element ) } else { let tmp = format_ident!("__S{}", u_inner); quote! { <#tmp as ::bake_rl::core::env::space::Space>::Element } }}).collect()).collect();


    let element_doc = format!("element of struct space {} (alias). generated by attr-macro `batched_struct_space`", quote!{#name});
    let generic_element_doc = format!("element of generalized struct space {}Generic. generated by attr-macro `batched_struct_space`", quote! {#name});
    let field_transform_docs: Vec<String> = field_idents.iter().map(|f| format!("returns `BatchedSpaceTransform` where given `transformer` is applied to field {}", f.clone())).collect();

    let mut transform_items = Vec::new();
    for u in 0..field_idents.len() {
        let field_transform_ident = field_transform_idents[u].clone();
        let gk = &generic_ty_idents[u];
        let field_transform_struct_ident = &field_transform_struct_idents[u];
        let field_transform_struct_output_space = field_transform_struct_output_spaces[u].clone();
        let field_transform_struct_output_space_struct = field_transform_struct_output_space_structs[u].clone();
        let field_transform_struct_output_element = field_transform_struct_output_elements[u].clone();
        let field_transform_doc = field_transform_docs[u].clone();
        transform_items.push(quote! {
            #[derive(Debug, Clone)]
            #vis struct #field_transform_struct_ident<BatchedTransformer> {
                transformer: BatchedTransformer,
            }

            impl<#(#generic_ty_idents: ::bake_rl::core::env::space::BatchedSpace, )* BatchedTransformer> ::bake_rl::core::env::space_transform::BatchedSpaceTransform<#generalized_space_ident<#(#generic_ty_idents,)*>> for #field_transform_struct_ident<BatchedTransformer>
            where
                BatchedTransformer: ::bake_rl::core::env::space_transform::BatchedSpaceTransform<#gk>,
            {
                type Applied = #generalized_space_ident<#(#field_transform_struct_output_space, )*>;

                fn transform_space(&self, applicant: &#generalized_space_ident<#(#generic_ty_idents,)*>) -> Self::Applied {
                    Self::Applied {
                        #(
                            #field_idents: #field_transform_struct_output_space_struct,
                        )*
                    }
                }

                fn transform_element(&mut self, applicant: &#generalized_space_ident<#(#generic_ty_idents,)*>, element: <#generalized_space_ident<#(#generic_ty_idents,)*> as ::bake_rl::core::env::space::BatchedSpace>::Element) -> <Self::Applied as ::bake_rl::core::env::space::BatchedSpace>::Element {
                    #generalized_space_element_ident {
                        #(
                            #field_idents: #field_transform_struct_output_element,
                        )*
                    }
                }
            }

            impl<#(#generic_ty_idents: ::bake_rl::core::env::space::BatchedSpace,)*> #generalized_space_ident<#(#generic_ty_idents,)*> {
                #[doc = #field_transform_doc] 
                pub fn #field_transform_ident<BatchedTransformer: ::bake_rl::core::env::space_transform::BatchedSpaceTransform<#gk>>(transformer: BatchedTransformer) -> #field_transform_struct_ident<BatchedTransformer> {
                    #field_transform_struct_ident::<BatchedTransformer> {
                        transformer,
                    }
                }
            }
        });
    }

    let token = quote! {
        #vis type #name #ty_generics = #generalized_space_ident<#(#field_tys, )*>;
        #[doc = #element_doc]
        #vis type #element_alias_ident #ty_generics = #generalized_space_element_ident<#(<#field_tys as ::bake_rl::core::env::space::BatchedSpace>::Element, )*>;

        #(
            #attrs
        )*
        #[derive(Debug, Clone)]
        #vis struct #generalized_space_ident<#(#generic_ty_idents: ::bake_rl::core::env::space::BatchedSpace, )*> {
            #(
                #(
                    #field_attrs
                )*
                #field_vis #field_idents: #generic_ty_idents,
            )*
        }

        #[doc = #generic_element_doc]
        #[derive(::bake_rl::core::data::BatchOps, Debug, Clone)]
        #vis struct #generalized_space_element_ident<#(#generic_ty_idents, )*> {
            #(
                #field_vis #field_idents: #generic_ty_idents,
            )*
        }

        #(#transform_items)*

        impl<#(#generic_ty_idents: ::bake_rl::core::env::space::BatchedSpace,)*> ::bake_rl::core::env::space::BatchedSpace for #generalized_space_ident<#(#generic_ty_idents,)*>{
            type Element = #generalized_space_element_ident<#(<#generic_ty_idents as ::bake_rl::core::env::space::BatchedSpace>::Element, )*>;

            fn sample(&self) -> Self::Element {
                Self::Element {
                    #(#field_idents: ::bake_rl::core::env::space::BatchedSpace::sample(&self.#field_idents),)*
                }
            }

            fn device(&self) -> ::bake_rl::burn::prelude::Device {
                ::bake_rl::core::env::space::BatchedSpace::device(&self.#fst_field)
            }
        }

        
    };

    Ok(token)
}