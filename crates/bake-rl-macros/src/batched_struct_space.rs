use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::{Data, DeriveInput, Fields, Ident, Type};

pub(crate) fn expand(ast: &DeriveInput) -> syn::Result<TokenStream> {
    let name = &ast.ident;

    let fields = match &ast.data {
        Data::Struct(s) => match &s.fields {
            Fields::Named(f) => &f.named,
            _ => {
                return Err(syn::Error::new_spanned(name, "BatchedStructSpace requires a struct with named fields"));
            }
        },
        _ => {
            return Err(
                syn::Error::new_spanned(
                    name,
                    "BatchedStructSpace can only be derived for struct currently"
                )
            );
        }
    };

    if fields.is_empty() {
        return Err(syn::Error::new_spanned(name, "BatchedStructSpace requires at least one field"));
    }

    let (impl_generics, ty_generics, where_clause) = ast.generics.split_for_impl();
    let field_idents: Vec<Ident> = fields.iter().map(|f| f.ident.clone().unwrap()).collect();
    let field_tys: Vec<Type> = fields.iter().map(|f| f.ty.clone()).collect();

    let element_doc = format!("element of batched struct space {}. generated by proc-macro `BatchedStructSpace`", quote! {#name});
    let element_ident = format_ident!("{}Element", name);

    let fst_field = field_idents[0].clone();

    Ok(quote! {
        #[doc = #element_doc]
        #[derive(::bake_rl::core::data::BatchOps, Debug, Clone)]
        pub struct #element_ident {
            #(
                ///
                pub #field_idents: <#field_tys as ::bake_rl::core::env::space::BatchedSpace>::Element,
            )*
        }

        impl #impl_generics ::bake_rl::core::env::space::BatchedSpace for #name #ty_generics #where_clause {
            type Element = #element_ident;

            fn sample(&self) -> Self::Element {
                Self::Element {
                    #(#field_idents: ::bake_rl::core::env::space::BatchedSpace::sample(&self.#field_idents),)*
                }
            }

            fn device(&self) -> ::bake_rl::burn::prelude::Device {
                ::bake_rl::core::env::space::BatchedSpace::device(&self.#fst_field)
            }
        }
    })
}