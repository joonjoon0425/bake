use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::{Data, DeriveInput, Fields, Ident, Type};

pub(crate) fn expand(ast: &DeriveInput) -> syn::Result<TokenStream> {
    let name = &ast.ident;

    let fields = match &ast.data {
        Data::Struct(s) => match &s.fields {
            Fields::Named(f) => &f.named,
            _ => {
                return Err(syn::Error::new_spanned(name, "StructSpace requires a struct with named fields"));
            }
        },
        _ => {
            return Err(
                syn::Error::new_spanned(
                    name,
                    "StructSpace can only be derived for struct currently"
                )
            );
        }
    };

    if fields.is_empty() {
        return Err(syn::Error::new_spanned(name, "StructSpace requires at least one field"));
    }

    let (impl_generics, ty_generics, where_clause) = ast.generics.split_for_impl();
    let field_idents: Vec<Ident> = fields.iter().map(|f| f.ident.clone().unwrap()).collect();
    let field_tys: Vec<Type> = fields.iter().map(|f| f.ty.clone()).collect();

    let element_doc = format!("element of struct space {}. generated by proc-macro `StructSpace`", quote! {#name});
    let element_ident = format_ident!("{}Element", name);

    Ok(quote! {
        #[doc = #element_doc]
        #[derive(Debug, Clone)]
        pub struct #element_ident #impl_generics {
            #(
                ///
                pub #field_idents: <#field_tys as ::bake_rl::core::env::space::Space>::Element,
            )*
        }

        impl #impl_generics ::bake_rl::core::env::space::Space for #name #ty_generics #where_clause {
            type Element = #element_ident #ty_generics;

            fn sample<R: ::bake_rl::rand::Rng>(&self, rng: &mut R) -> Self::Element {
                Self::Element {
                    #(#field_idents: ::bake_rl::core::env::space::Space::sample(&self.#field_idents, rng),)*
                }
            }
        }
    })
}